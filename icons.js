// the name only appears if the pointer rests on an icon, so sweeping across the grid stays quiet
const ICON_TIP_DELAY = 2000;
let iconTipTimer = null;
let iconTipFor = null;

function hideIconTip() {
  clearTimeout(iconTipTimer);
  iconTipFor = null;
  iconTip.classList.remove("show");
}

function showIconTip(btn) {
  iconTip.textContent = ICON_NAMES[btn.dataset.icon];
  const r = btn.getBoundingClientRect();
  const w = iconTip.offsetWidth;
  const left = Math.min(window.innerWidth - w - 8, Math.max(8, r.left + r.width / 2 - w / 2));
  iconTip.style.left = left + "px";
  iconTip.style.top = r.top - iconTip.offsetHeight - 6 + "px";
  iconTip.classList.add("show");
}

document.addEventListener("mouseover", (e) => {
  const btn = e.target.closest(".icon-opt");
  if (btn === iconTipFor) return;
  hideIconTip();
  if (!btn || !ICON_NAMES[btn.dataset.icon]) return;
  iconTipFor = btn;
  iconTipTimer = setTimeout(() => showIconTip(btn), ICON_TIP_DELAY);
});
document.addEventListener("scroll", hideIconTip, true);
document.addEventListener("mousedown", hideIconTip);
