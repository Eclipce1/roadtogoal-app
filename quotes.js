function dayNumber(date = new Date()) {
  return Math.floor(
    Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) / 86400000
  );
}

function quoteOfTheDay(goal, step, finished, woop = {}, salt = 7) {
  const hasGoal = !isPlaceholderGoal(goal);
  const clean = (t) => (t || "").trim().replace(/[.!]+$/, "");
  const low = (t) => (t ? t.charAt(0).toLowerCase() + t.slice(1) : t);
  const fill = {
    "{goal}": hasGoal ? goal.trim() : "",
    "{step}": step || "",
    "{obstacle}": low(cleanObstacle(woop.obstacle)),
    "{action}": low(cleanAction(woop.plan)),
    "{outcome}": low(clean(woop.outcome)),
  };
  // only phrases whose placeholders we can actually fill
  const usable = (q) => Object.keys(fill).every((k) => !q.includes(k) || fill[k]);
  const pool = (finished ? FINISH_QUOTES : QUOTES).filter(usable);
  // multiply by a prime so consecutive days jump around the list
  const q = pool[(dayNumber() * salt) % pool.length];
  return Object.entries(fill).reduce((acc, [k, v]) => acc.split(k).join(v), q);
}
